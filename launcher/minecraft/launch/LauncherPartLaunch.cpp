LauncherPartLaunch::LauncherPartLaunch(LaunchTask* parent)
    : LaunchStep(parent)
    , m_process(parent->instance()->getJavaVersion().defaultsToUtf8() ? QStringConverter::Utf8 : QStringConverter::System)
{
    if (parent->instance()->settings()->get("CloseAfterLaunch").toBool()) {
        static const QRegularExpression s_settingUser(".*Setting user.+", QRegularExpression::CaseInsensitiveOption);
        std::shared_ptr<QMetaObject::Connection> connection{ new QMetaObject::Connection };
        *connection =
            connect(&m_process, &LoggedProcess::log, this, [connection](const QStringList& lines, [[maybe_unused]] MessageLevel level) {
                qDebug() << lines;
                if (lines.filter(s_settingUser).length() != 0) {
                    APPLICATION->closeAllWindows();
                    disconnect(*connection);
                }
            });
    }

    connect(&m_process, &LoggedProcess::log, this, &LauncherPartLaunch::logLines);
    connect(&m_process, &LoggedProcess::stateChanged, this, &LauncherPartLaunch::on_state);
}

void LauncherPartLaunch::executeTask()
{
    QString jarPath = APPLICATION->getJarPath("NewLaunch.jar");
    if (jarPath.isEmpty()) {
        const char* reason = QT_TR_NOOP("Launcher library could not be found. Please check your installation.");
        emit logLine(tr(reason), MessageLevel::Fatal);
        emitFailed(tr(reason));
        return;
    }

    auto instance = m_parent->instance();

    QString legacyJarPath;
    if (instance->getLauncher() == "legacy" || instance->shouldApplyOnlineFixes()) {
        legacyJarPath = APPLICATION->getJarPath("NewLaunchLegacy.jar");
        if (legacyJarPath.isEmpty()) {
            const char* reason = QT_TR_NOOP("Legacy launcher library could not be found. Please check your installation.");
            emit logLine(tr(reason), MessageLevel::Fatal);
            emitFailed(tr(reason));
            return;
        }
    }

    m_launchScript = instance->createLaunchScript(m_session, m_targetToJoin);
    QStringList args = instance->javaArguments();
    QString allArgs = args.join(" ");
    emit logLine("Java arguments:\n  " + m_parent->censorPrivateInfo(allArgs) + "\n", MessageLevel::Launcher);

    auto javaPath = FS::ResolveExecutable(instance->settings()->get("JavaPath").toString());

#ifdef Q_OS_WIN32
    QString gpuPref = instance->settings()->get("GpuPreference").toString();
    QString gpuInjectDllPath;

    if (gpuPref != "default") {
        // Write GPU inject DLL to temp
        gpuInjectDllPath = QDir::temp().absoluteFilePath("prismlauncher_gpuinject.dll");
        {
            QFile dllFile(gpuInjectDllPath);
            if (dllFile.open(QIODevice::WriteOnly)) {
                dllFile.write(reinterpret_cast<const char*>(g_gpuInjectDll), sizeof(g_gpuInjectDll));
                dllFile.close();
            } else {
                gpuInjectDllPath.clear();
                emit logLine("GPU Preference: Could not write inject DLL\n", MessageLevel::Warning);
            }
        }

        // Set GPU preference via Windows Graphics Settings registry using Win32 API directly.
        // QSettings is not used because it converts all backslashes to forward slashes.
        HKEY hKey;
        DWORD disposition;
        LSTATUS status = RegCreateKeyExW(
            HKEY_CURRENT_USER,
            L"SOFTWARE\\Microsoft\\DirectX\\UserGpuPreferences",
            0,
            NULL,
            REG_OPTION_NON_VOLATILE,
            KEY_SET_VALUE,
            NULL,
            &hKey,
            &disposition
        );
        if (status == ERROR_SUCCESS) {
            std::wstring subKeyW = QDir::toNativeSeparators(javaPath).toStdWString();
            std::wstring valueW;
            if (gpuPref == "high_performance") {
                valueW = L"GpuPreference=2;";
                emit logLine("GPU Preference: Set javaw.exe to High Performance GPU\n", MessageLevel::Launcher);
            } else if (gpuPref == "integrated") {
                valueW = L"GpuPreference=1;";
                emit logLine("GPU Preference: Set javaw.exe to Integrated GPU\n", MessageLevel::Launcher);
            } else {
                valueW = L"GpuPreference=2;"; // Default fallback for specific GPUs
                emit logLine(QString("GPU Preference: Set javaw.exe to use specific GPU %1\n").arg(gpuPref), MessageLevel::Launcher);

                // Try to detect if the chosen specific GPU is the Power Saving/Integrated GPU
                ComPtr<IDXGIFactory6> factory;
                if (SUCCEEDED(CreateDXGIFactory1(IID_PPV_ARGS(&factory)))) {
                    ComPtr<IDXGIAdapter> adapterMin;
                    if (SUCCEEDED(factory->EnumAdapterByGpuPreference(0, DXGI_GPU_PREFERENCE_MINIMUM_POWER, IID_PPV_ARGS(&adapterMin)))) {
                        DXGI_ADAPTER_DESC desc;
                        if (SUCCEEDED(adapterMin->GetDesc(&desc))) {
                            QString minGpuName = QString::fromWCharArray(desc.Description);
                            if (gpuPref == minGpuName) {
                                valueW = L"GpuPreference=1;";
                                emit logLine(QString("GPU Preference: Specific GPU %1 detected as Integrated GPU\n").arg(gpuPref), MessageLevel::Launcher);
                            }
                        }
                    }
                }
            }

            RegSetValueExW(
                hKey,
                subKeyW.c_str(),
                0,
                REG_SZ,
                reinterpret_cast<const BYTE*>(valueW.c_str()),
                static_cast<DWORD>((valueW.size() + 1) * sizeof(wchar_t))
            );
            // Delete the incorrect forward-slash version if it exists
            std::wstring forwardSubKeyW = QDir::cleanPath(javaPath).toStdWString();
            RegDeleteValueW(hKey, forwardSubKeyW.c_str());
            RegCloseKey(hKey);
        } else {
            emit logLine("GPU Preference: Failed to open/create DirectX registry key\n", MessageLevel::Warning);
        }
    } else {
        // Reset registry preference using Win32 API
        HKEY hKey;
        LSTATUS status = RegOpenKeyExW(
            HKEY_CURRENT_USER,
            L"SOFTWARE\\Microsoft\\DirectX\\UserGpuPreferences",
            0,
            KEY_SET_VALUE,
            &hKey
        );
        if (status == ERROR_SUCCESS) {
            std::wstring nativeSubKeyW = QDir::toNativeSeparators(javaPath).toStdWString();
            std::wstring forwardSubKeyW = QDir::cleanPath(javaPath).toStdWString();
            RegDeleteValueW(hKey, nativeSubKeyW.c_str());
            RegDeleteValueW(hKey, forwardSubKeyW.c_str());
            RegCloseKey(hKey);
        }
    }
#endif

    m_process.setProcessEnvironment(instance->createLaunchEnvironment());

    // make detachable - this will keep the process running even if the object is destroyed
    m_process.setDetachable(true);

    auto classPath = instance->getClassPath();
    classPath.prepend(jarPath);

    if (!legacyJarPath.isEmpty())
        classPath.prepend(legacyJarPath);

    auto natPath = instance->getNativePath();
#ifdef Q_OS_WIN
    natPath = FS::getPathNameInLocal8bit(natPath);
#endif
    args << "-Djava.library.path=" + natPath;

    args << "-cp";
#ifdef Q_OS_WIN
    QStringList processed;
    for (auto& item : classPath) {
        processed << FS::getPathNameInLocal8bit(item);
    }
    args << processed.join(';');
#else
    args << classPath.join(':');
#endif
    args << "org.prismlauncher.EntryPoint";

    qDebug() << args.join(' ');

    QString wrapperCommandStr = instance->getWrapperCommand().trimmed();
    if (!wrapperCommandStr.isEmpty()) {
        wrapperCommandStr = m_parent->substituteVariables(wrapperCommandStr);
        auto wrapperArgs = Commandline::splitArgs(wrapperCommandStr);
        auto wrapperCommand = wrapperArgs.takeFirst();
        auto realWrapperCommand = QStandardPaths::findExecutable(wrapperCommand);
        if (realWrapperCommand.isEmpty()) {
            const char* reason = QT_TR_NOOP("The wrapper command \"%1\" couldn't be found.");
            emit logLine(QString(reason).arg(wrapperCommand), MessageLevel::Fatal);
            emitFailed(tr(reason).arg(wrapperCommand));
            return;
        }
        emit logLine("Wrapper command is:\n" + wrapperCommandStr + "\n\n", MessageLevel::Launcher);
        args.prepend(javaPath);
        m_process.start(wrapperCommand, wrapperArgs + args);
    } else {
        m_process.start(javaPath, args);
    }

#ifdef Q_OS_WIN32
    if (!gpuInjectDllPath.isEmpty()) {
        HANDLE hProcess = OpenProcess(PROCESS_ALL_ACCESS, FALSE, static_cast<DWORD>(m_process.processId()));
        if (hProcess) {
            if (injectDll(hProcess, gpuInjectDllPath)) {
                emit logLine("GPU Preference: Injected GPU selector DLL into Java process\n", MessageLevel::Launcher);
            } else {
                emit logLine("GPU Preference: Failed to inject GPU selector DLL\n", MessageLevel::Warning);
            }
            CloseHandle(hProcess);
        } else {
            emit logLine("GPU Preference: Could not open Java process for DLL injection\n", MessageLevel::Warning);
        }
    }
#endif

#ifdef Q_OS_LINUX
    if (instance->settings()->get("EnableFeralGamemode").toBool() && APPLICATION->capabilities() & Application::SupportsGameMode) {
        auto pid = m_process.processId();
        if (pid) {
            gamemode_request_start_for(pid);
        }
    }
#endif
}

void LauncherPartLaunch::on_state(LoggedProcess::State state)
{
    switch (state) {
        case LoggedProcess::FailedToStart: {
            //: Error message displayed if instace can't start
            const char* reason = QT_TR_NOOP("Could not launch Minecraft: %1");
            emit logLine(QString(reason).arg(m_process.errorString()), MessageLevel::Fatal);
            emitFailed(tr(reason).arg(m_process.errorString()));
            return;
        }
        case LoggedProcess::Aborted:
        case LoggedProcess::Crashed: {
            m_parent->setPid(-1);
            m_parent->instance()->setMinecraftRunning(false);
            emitFailed(tr("Game crashed."));
            return;
        }
        case LoggedProcess::Finished: {
            auto instance = m_parent->instance();
            if (instance->settings()->get("CloseAfterLaunch").toBool())
                APPLICATION->showMainWindow();

            m_parent->setPid(-1);
            m_parent->instance()->setMinecraftRunning(false);
            // if the exit code wasn't 0, report this as a crash
            auto exitCode = m_process.exitCode();
            if (exitCode != 0) {
                emitFailed(tr("Game crashed."));
                return;
            }
            // FIXME: make this work again
            //  m_postlaunchprocess.processEnvironment().insert("INST_EXITCODE", QString(exitCode));
            //  run post-exit
            emitSucceeded();
            break;
        }
        case LoggedProcess::Running:
            emit logLine(QString("Minecraft process ID: %1\n\n").arg(m_process.processId()), MessageLevel::Launcher);
            m_parent->setPid(m_process.processId());
            // send the launch script to the launcher part
            m_process.write(m_launchScript.toUtf8());

            mayProceed = true;
            emit readyForLaunch();
            break;
        default:
            break;
    }
}

void LauncherPartLaunch::setWorkingDirectory(const QString& wd)
{
    m_process.setWorkingDirectory(wd);
}

void LauncherPartLaunch::proceed()
{
    if (mayProceed) {
        m_parent->instance()->setMinecraftRunning(true);
        QString launchString("launch\n");
        m_process.write(launchString.toUtf8());
        mayProceed = false;
    }
}

bool LauncherPartLaunch::abort()
{
    if (mayProceed) {
        mayProceed = false;
        QString launchString("abort\n");
        m_process.write(launchString.toUtf8());
    } else {
        auto state = m_process.state();
        if (state == LoggedProcess::Running || state == LoggedProcess::Starting) {
            m_process.kill();
        }
    }
    return true;
}
